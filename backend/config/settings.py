"""
Django settings for the Collings-stack boilerplate.

Mirrors the Collings-CRM-BE stack: DRF + SimpleJWT auth, CORS for the CRA
frontend, Channels/Daphne (ASGI), Celery + Redis, Postgres (SQLite fallback for
local first-run), WhiteNoise static, and optional S3 media + Sentry.

Everything environment-specific is read from the environment (.env in local dev,
config vars on Heroku). See .env.example.
"""
